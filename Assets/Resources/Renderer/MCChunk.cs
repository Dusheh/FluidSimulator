    int GetVertexIndex(int vx, int vy, int vz, int edge)
    {
        var info = edgeInfo[edge];
        int gx = vx + info.dx;
        int gy = vy + info.dy;
        int gz = vz + info.dz;
        if (info.dir == 0)      // X边
            return XEdgeIndex(gx, gy, gz);
        else if (info.dir == 1) // Y边
            return YEdgeIndex(gx, gy, gz);
        else                    // Z边
            return ZEdgeIndex(gx, gy, gz);
    }
    int XEdgeIndex(int x, int y, int z) => z * (size.y * (size.x - 1)) + y * (size.x - 1) + x;
    int YEdgeIndex(int x, int y, int z) => cX + z * (size.x * (size.y - 1)) + y * size.x + x;
    int ZEdgeIndex(int x, int y, int z) => cX + cY + z * (size.x * size.y) + y * size.x + x;

